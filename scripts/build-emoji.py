#!/usr/bin/env python3
"""Builds Resources/emoji.txt: the emoji offered after a candidate ("笑" → 🤣🥰😼).

Source: the Traditional Chinese emoji names and keywords of Unicode CLDR
(cldr-json, annotations/zh-Hant; Unicode License v3). Only words that are phrases in
Resources/lexicon.txt are kept (the others can never be a candidate).

    scripts/build-emoji.py                 downloads the CLDR file
    scripts/build-emoji.py annotations.json

Rules: a word gets the emoji named after it first (CLDR's short name), then the ones that
list it as a keyword, at most MAX_PER_WORD. A keyword shared by more than MAX_SHARED emoji
("臉", "動物") is too vague and only gives the emoji named after it. Skin-tone and
gender variants are left out.
"""
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = ("https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/"
       "cldr-annotations-full/annotations/zh-Hant/annotations.json")
MAX_PER_WORD = 5
MAX_SHARED = 8


def is_emoji(s):
    cps = [ord(c) for c in s]
    if any(0x1F3FB <= c <= 0x1F3FF for c in cps):        # skin tones
        return False
    if 0x200D in cps and any(c in (0x2640, 0x2642) for c in cps):   # gender variants
        return False
    first = cps[0]
    return first >= 0x1F000 or 0x2600 <= first <= 0x27BF or first in (0x2B50, 0x2B55, 0x231A, 0x231B, 0x23F0, 0x23F3)


def shown(s):
    """A lone symbol from the BMP ranges (❤, ☀) needs VS16 to be drawn as an emoji."""
    return s + "️" if len(s) == 1 and ord(s) < 0x10000 else s


def is_chinese(word):
    return all("㐀" <= c <= "鿿" for c in word)


def main():
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL) as r:
            data = json.loads(r.read().decode("utf-8"))
    annotations = data["annotations"]["annotations"]

    phrases = set()
    for line in (ROOT / "Resources" / "lexicon.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            parts = line.split(" ")
            if len(parts) >= 2:
                phrases.add(parts[1])

    named, listed = {}, {}
    for emoji, v in annotations.items():
        if not is_emoji(emoji):
            continue
        for name in v.get("tts", []):
            named.setdefault(name, []).append(emoji)
        for word in v.get("default", []):
            listed.setdefault(word, []).append(emoji)

    lines = []
    for word in sorted(set(named) | set(listed)):
        if not is_chinese(word) or word not in phrases:
            continue
        out = list(named.get(word, []))
        others = listed.get(word, [])
        if len(others) <= MAX_SHARED:
            out += [e for e in others if e not in out]
        if out:
            lines.append(word + "\t" + " ".join(shown(e) for e in out[:MAX_PER_WORD]))

    header = ("# Generated by scripts/build-emoji.py from Unicode CLDR (annotations/zh-Hant,\n"
              "# Unicode License v3). Format: <word>\\t<emoji> <emoji> ...\n")
    (ROOT / "Resources" / "emoji.txt").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)} words → Resources/emoji.txt")


if __name__ == "__main__":
    main()
