#!/usr/bin/env python3
"""Builds Resources/emoji.txt: the symbols and emoji offered after a candidate
("笑" → 🤣🥰😼, "星" → ★☆, "乘" → ×).

Sources, in this order for each word:
1. scripts/symbols-extra.txt: common symbols CLDR doesn't name (★ ♥ ♪ ✓ ℃ …)
2. the Traditional Chinese names and keywords of Unicode CLDR (cldr-json,
   annotations/zh-Hant; Unicode License v3): its symbols (shapes, math, arrows, ©, €…),
   then its emoji
Only words that are phrases in Resources/lexicon.txt are kept (the others can never be a
candidate).

    scripts/build-emoji.py                 downloads the CLDR file
    scripts/build-emoji.py annotations.json

Rules: within the CLDR symbols and within the emoji, a word gets the one named after it
first (CLDR's short name), then the ones that list it as a keyword; at most MAX_PER_WORD in
all. A keyword shared by more than MAX_SHARED ("臉", "動物") is too vague and only gives
the one named after it. Left out: skin-tone and gender variants, keycaps (一 → 1⃣),
punctuation and brackets (the punctuation keys and the symbol table have them), accents,
and the currency signs nobody uses.
"""
import json
import sys
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = ("https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/"
       "cldr-annotations-full/annotations/zh-Hant/annotations.json")
MAX_PER_WORD = 5
MAX_SHARED = 8


def is_emoji(s):
    cps = [ord(c) for c in s]
    if any(0x1F3FB <= c <= 0x1F3FF for c in cps):        # skin tones
        return False
    if 0x200D in cps and any(c in (0x2640, 0x2642) for c in cps):   # gender variants
        return False
    first = cps[0]
    return first >= 0x1F000 or 0x2600 <= first <= 0x27BF or first in (0x2B50, 0x2B55, 0x231A, 0x231B, 0x23F0, 0x23F3)


KEEP_CURRENCY = set("$¢£¥€₩")


def is_symbol(s):
    """A CLDR entry that isn't an emoji but is worth offering: shapes, math, arrows, ©…"""
    if is_emoji(s) or len(s) != 1:          # keycaps, gender sequences, …
        return False
    if any(0x1F3FB <= ord(c) <= 0x1F3FF for c in s):
        return False
    cat = unicodedata.category(s)
    if cat.startswith("P") or cat in ("Sk", "Mn", "Lm"):      # punctuation, accents
        return False
    if cat == "Sc" and s not in KEEP_CURRENCY:
        return False
    return not ("\u0600" <= s <= "\u06ff")                  # Arabic


def shown(s):
    """A lone symbol from the BMP ranges (❤, ☀) needs VS16 to be drawn as an emoji."""
    return s + "️" if len(s) == 1 and ord(s) < 0x10000 else s


def is_chinese(word):
    return all("㐀" <= c <= "鿿" for c in word)


def main():
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL) as r:
            data = json.loads(r.read().decode("utf-8"))
    annotations = data["annotations"]["annotations"]

    phrases = set()
    for line in (ROOT / "Resources" / "lexicon.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            parts = line.split(" ")
            if len(parts) >= 2:
                phrases.add(parts[1])

    def index(keep):
        named, listed = {}, {}
        for char, v in annotations.items():
            if not keep(char):
                continue
            for name in v.get("tts", []):
                named.setdefault(name, []).append(char)
            for word in v.get("default", []):
                listed.setdefault(word, []).append(char)
        return named, listed

    def lookup(tables, word):
        named, listed = tables
        out = list(named.get(word, []))
        others = listed.get(word, [])
        if len(others) <= MAX_SHARED:
            out += [c for c in others if c not in out]
        return out

    extra = {}
    for line in (ROOT / "scripts" / "symbols-extra.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#") and "\t" in line:
            word, chars = line.split("\t", 1)
            extra[word] = chars.split()

    symbols, emoji = index(is_symbol), index(is_emoji)
    words = set(extra) | set().union(*symbols, *emoji)
    lines = []
    for word in sorted(words):
        if not is_chinese(word) or word not in phrases:
            continue
        out = []
        for c in extra.get(word, []) + lookup(symbols, word) + [shown(e) for e in lookup(emoji, word)]:
            if c not in out:
                out.append(c)
        if out:
            lines.append(word + "\t" + " ".join(out[:MAX_PER_WORD]))
    missing = sorted(w for w in extra if w not in phrases)
    if missing:
        print("not in the lexicon (left out):", " ".join(missing))

    header = ("# Generated by scripts/build-emoji.py from scripts/symbols-extra.txt and Unicode CLDR\n"
              "# (annotations/zh-Hant, Unicode License v3). Format: <word>\\t<symbol or emoji> ...\n")
    (ROOT / "Resources" / "emoji.txt").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)} words → Resources/emoji.txt")


if __name__ == "__main__":
    main()
